// The Android app needs the Android SDK. Without it (e.g. a plain cloud container),
// only :core is built so its tests still run.
val localProps = file("local.properties")
val hasSdk = System.getenv("ANDROID_HOME") != null ||
    System.getenv("ANDROID_SDK_ROOT") != null ||
    (localProps.exists() && localProps.readText().contains("sdk.dir"))
if (hasSdk) include(":app") else println("Android SDK not found: building :core only")
